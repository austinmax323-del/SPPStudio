        }

        return lines
    }

    private func orionCreateExpr(for component: SPPUIComponent) -> String {
        switch component.kind {
        case .label:           return "UILabel()"
        case .button:          return "UIButton(type: .system)"
        case .textField:       return "UITextField()"
        case .imageView:       return "UIImageView()"
        case .stackView:
            let axis = component.properties["axis"].flatMap { StackAxis(rawValue: $0) } ?? .vertical
            return axis == .horizontal
                ? "{ let sv = UIStackView(); sv.axis = .horizontal; return sv }()"
                : "{ let sv = UIStackView(); sv.axis = .vertical; return sv }()"
        case .scrollView:      return "UIScrollView()"
        case .tableView:       return "UITableView(frame: .zero, style: .plain)"
        case .collectionView:
            return "UICollectionView(frame: .zero, collectionViewLayout: UICollectionViewFlowLayout())"
        case .switch_:         return "UISwitch()"
        case .slider:          return "UISlider()"
        case .progressView:    return "UIProgressView(progressViewStyle: .default)"
        case .activityIndicator: return "UIActivityIndicatorView(style: .medium)"
        case .view, .custom:   return "UIView()"
        }
    }

    private func orionKindConfig(_ component: SPPUIComponent, varName: String, indent: Int) -> [String] {
        let pad = String(repeating: "    ", count: indent)
        var lines: [String] = []
        switch component.kind {
        case .label:
            let text = component.properties["text"] ?? component.name
            lines.append("\(pad)(\(varName) as! UILabel).text = \"\(escaped(text))\"")
            if let fg = component.style.foregroundColor {
                lines.append("\(pad)(\(varName) as! UILabel).textColor = \(fg.uiColorLiteral)")
            }
            if let font = component.style.font {
                lines.append("\(pad)(\(varName) as! UILabel).font = UIFont(name: \"\(font.family)\", size: \(font.size)) ?? .systemFont(ofSize: \(font.size))")
            }
        case .button:
            let title = component.properties["text"] ?? component.name
            lines.append("\(pad)(\(varName) as! UIButton).setTitle(\"\(escaped(title))\", for: .normal)")
            if let fg = component.style.foregroundColor {
                lines.append("\(pad)(\(varName) as! UIButton).setTitleColor(\(fg.uiColorLiteral), for: .normal)")
            }
        case .textField:
            let placeholder = component.properties["placeholder"] ?? ""
            lines.append("\(pad)(\(varName) as! UITextField).placeholder = \"\(escaped(placeholder))\"")
        case .imageView:
            let imageName = component.properties["imageName"] ?? ""
            if !imageName.isEmpty {
                if imageName.hasPrefix("system:") {
                    let sysName = String(imageName.dropFirst("system:".count))
                    lines.append("\(pad)(\(varName) as! UIImageView).image = UIImage(systemName: \"\(sysName)\")")
                } else {
                    lines.append("\(pad)(\(varName) as! UIImageView).image = UIImage(named: \"\(imageName)\")")
                }
            }
        case .stackView:
            let spacing = Double(component.properties["spacing"] ?? "8") ?? 8
            lines.append("\(pad)(\(varName) as! UIStackView).spacing = \(spacing)")
        case .slider:
            let min = Float(component.properties["min"] ?? "0") ?? 0
            let max = Float(component.properties["max"] ?? "100") ?? 100
            lines.append("\(pad)(\(varName) as! UISlider).minimumValue = \(min)")
            lines.append("\(pad)(\(varName) as! UISlider).maximumValue = \(max)")
        case .progressView:
            let progress = Float(component.properties["progress"] ?? "0.5") ?? 0.5
            lines.append("\(pad)(\(varName) as! UIProgressView).progress = \(progress)")
        case .activityIndicator:
            lines.append("\(pad)(\(varName) as! UIActivityIndicatorView).startAnimating()")
        default:
            break
        }
        return lines
    }
}

// MARK: - String helpers (file-private)

/// Turns an arbitrary name into a PascalCase Swift type identifier.
private func swiftTypeName(_ raw: String) -> String {
    let words = raw
        .components(separatedBy: CharacterSet.alphanumerics.inverted)
        .filter { !$0.isEmpty }
    return words.map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}

/// Turns an arbitrary name into a camelCase Swift identifier.
private func camelCase(_ raw: String) -> String {
    let pascal = swiftTypeName(raw)
    guard !pascal.isEmpty else { return "" }
    return pascal.prefix(1).lowercased() + pascal.dropFirst()
}

/// Escapes characters that would break a Swift or ObjC string literal.
private func escaped(_ string: String) -> String {
    string
        .replacingOccurrences(of: "\\", with: "\\\\")
        .replacingOccurrences(of: "\"", with: "\\\"")
        .replacingOccurrences(of: "\n", with: "\\n")
        .replacingOccurrences(of: "\r", with: "\\r")
        .replacingOccurrences(of: "\t", with: "\\t")
}
